const stored = (typeof localStorage !== "undefined" && localStorage.getItem("intvtt_lang")) ||
  (navigator.language?.toLowerCase().startsWith("en") ? "en" : "ru");

i18next.use(initReactI18next).init({
  resources,
  lng: stored === "en" ? "en" : "ru",
  fallbackLng: "ru",
  interpolation: { escapeValue: false },
});

export function setAppLanguage(lng: "ru" | "en") {
  i18next.changeLanguage(lng);
  try { localStorage.setItem("intvtt_lang", lng); } catch { /* ignore */ }
}

export default i18next;
